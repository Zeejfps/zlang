#!/usr/bin/env python3
"""Writes ui/gl/shaders_glsl.ctx: the GLSL files of ui/shaders as ctxlang string constants.

    embed_shaders.py SHADER_DIR OUT_FILE      (ui/tools/build_shaders runs it; OUT_FILE - is stdout)

It copies bytes and reads no ctxlang. Each shader becomes a `[_]c::String`, one literal a line
(GL joins the elements as they are), with every byte kept: `\\`, `"` and the bytes outside printable
ASCII are escaped, because a ctxlang literal holds ASCII only and the shaders' comments have UTF-8
in them, which a multi-line literal (no escapes) could not carry.
"""
import pathlib
import sys

# The shader files, in the order the constants are written; each constant is the file's name in capitals.
FILES = [
    "canvas_rect.vert.glsl", "canvas_rect.frag.glsl",
    "canvas_glyph.vert.glsl", "canvas_glyph.frag.glsl",
    "canvas_image.vert.glsl", "canvas_image.frag.glsl",
    "canvas_shape.vert.glsl", "canvas_shape.frag.glsl",
]

HEADER = """\
// Generated by ui/tools/build_shaders from ui/shaders/*.glsl (ui/tools/embed_shaders.py): do not edit.
// Change a shader file and run ui/tools/build_shaders; `ui/tools/build_shaders --check` fails while
// this file and the shaders differ.
//
// Each shader is its file's bytes, one literal a line, for glShaderSource to join.
namespace ui_gl {
"""


def escape_line(raw: bytes) -> str:
    out = []
    for b in raw:
        if b == 0x5C:
            out.append("\\\\")
        elif b == 0x22:
            out.append('\\"')
        elif b == 0x09:
            out.append("\\t")
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append("\\x%02X" % b)
    return "".join(out)


def make_constant(name: str, data: bytes) -> str:
    if b"\0" in data:
        raise SystemExit("embed_shaders.py: %s holds a NUL byte, which a C string cannot" % name)
    if b"\r" in data:
        raise SystemExit("embed_shaders.py: %s has a carriage return; the shaders keep LF line ends" % name)
    lines = data.split(b"\n")
    ends_with_newline = lines[-1] == b""
    if ends_with_newline:
        lines.pop()
    const = name.replace(".glsl", "").replace(".", "_").upper()
    out = ["    // ui/shaders/%s" % name, "    const %s: [_]c::String = [" % const]
    for i, line in enumerate(lines):
        newline = "\\n" if (i + 1 < len(lines) or ends_with_newline) else ""
        out.append('        "%s%s",' % (escape_line(line), newline))
    out.append("    ]")
    return "\n".join(out) + "\n"


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("usage: embed_shaders.py SHADER_DIR OUT_FILE")
    src = pathlib.Path(sys.argv[1])
    parts = [HEADER]
    for i, name in enumerate(FILES):
        if i > 0:
            parts.append("\n")
        parts.append(make_constant(name, (src / name).read_bytes()))
    parts.append("}\n")
    text = "".join(parts).encode("ascii")
    if sys.argv[2] == "-":
        sys.stdout.buffer.write(text)
    else:
        pathlib.Path(sys.argv[2]).write_bytes(text)


if __name__ == "__main__":
    main()
